JOSA = {
    "이가": ("이", "가"),
    "은는": ("은", "는"),
    "을를": ("을", "를"),
    "로": ("으로", "로"),
    "와과": ("과", "와"),
}
JONG_RIEUL = 8


def has_jong(word):
    if not word:
        return None
    c = word[-1]
    o = ord(c)
    if 0xAC00 <= o <= 0xD7A3:
        return ((o - 0xAC00) % 28) != 0
    if c.isalnum() and c.isascii():
        return None
    return None


def josa(word, kind):
    """받침에 맞는 조사를 붙여 돌려준다. 판단이 안 되는 끝글자(영문 등)는 받침 없음으로 본다."""
    hj = has_jong(word)
    if kind == "이라고":
        return word + ("이라고" if hj else "라고")
    with_j, without_j = JOSA[kind]
    if kind == "로":
        o = ord(word[-1]) if word else 0
        if 0xAC00 <= o <= 0xD7A3 and (o - 0xAC00) % 28 == JONG_RIEUL:
            return word + "로"
        return word + (with_j if hj else without_j)
    return word + (with_j if hj else without_j)


SLOT = re.compile(r"\{(\w+)(?::(\w+))?\}")


def render(tmpl, mapping):
    def rep(m):
        key, kind = m.group(1), m.group(2)
        if key == "W":          # 런타임에 사용자가 던진 욕 단어로 치환
            return "{W}"
        w = str(mapping[key])
        return josa(w, kind) if kind else w
    return SLOT.sub(rep, tmpl)


def cross(tmpl, **banks):
    keys = list(banks.keys())
    out = []
    stack = [({}, 0)]
    for vals in _product([banks[k] for k in keys]):
        out.append(render(tmpl, dict(zip(keys, vals))))
    return out


def _product(lists):
    if not lists:
        yield ()
        return
    head, rest = lists[0], lists[1:]
    for h in head:
        for r in _product(rest):
            yield (h,) + r


# ── 기존 코퍼스 문장(중복 방지용) ──────────────────────────────
def existing_lines():
    seen = set()
    for path in (CORPUS, DIALOGUES):
        if not os.path.exists(path):
            continue
        src = open(path, encoding="utf-8").read()
        for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', src):
            s = m.group(1)
            if len(s) < 6:
                continue
            seen.add(s.replace('\\"', '"'))
    return seen


EXISTING = existing_lines()
SEEN = set()


WORD_RE = re.compile(r"[가-힣A-Za-z]{3,}")


def quality_ok(s):
    """같은 단어가 두 번 나오면 대개 문장이 망가진다(호칭 중복·슬롯 중복)."""
    seen = set()
    for w in WORD_RE.findall(s):
        if w in seen:
            return False
        seen.add(w)
    if s.count("새끼") >= 2 or s.count("병신") >= 2 or s.count("찐따") >= 2:
        return False
    if re.search(r"야\s*[,.?]\s*야", s):
        return False
    return True


def pool(name, target, handcrafted, families):
    out = []

    def push(s):
        s = str(s).strip()
        if not s or len(s) > 88:
            return False
        if not quality_ok(s):
            return False
        if s in SEEN or s in EXISTING:
            return False
        SEEN.add(s)
        out.append(s)
        return True

    for s in handcrafted:
        push(s)
    cand = []
    for f in families:
        cand.extend(f)
    random.shuffle(cand)
    for s in cand:
        if len(out) >= target:
            break
        push(s)
    return out


